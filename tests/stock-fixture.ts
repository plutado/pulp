/**
 * A synthetic stock library for the tests (milestone 32): a few generated stills and sounds in the
 * folder layout a bought collection comes in. Every byte is made here, so no stock media ever
 * enters the repository or the test run.
 */

import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { deflateSync } from 'node:zlib';
import { encodePng } from '../src/core/png';

/** A small PNG of one color, with a gradient so no two are alike. */
function stillPng(r: number, g: number, b: number, w = 32, h = 18): Buffer {
  const rgba = new Uint8Array(w * h * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      rgba[i] = r; rgba[i + 1] = Math.min(255, g + x * 3); rgba[i + 2] = b; rgba[i + 3] = 255;
    }
  }
  return Buffer.from(encodePng(rgba, w, h, (bytes) => new Uint8Array(deflateSync(bytes))));
}

/** A short 16-bit mono WAV: a tone of `hz` for `seconds`. */
function toneWav(hz: number, seconds = 0.25, rate = 8000): Buffer {
  const n = Math.round(seconds * rate);
  const data = Buffer.alloc(n * 2);
  for (let i = 0; i < n; i++) data.writeInt16LE(Math.round(Math.sin((2 * Math.PI * hz * i) / rate) * 8000), i * 2);
  const head = Buffer.alloc(44);
  head.write('RIFF', 0); head.writeUInt32LE(36 + data.length, 4); head.write('WAVE', 8);
  head.write('fmt ', 12); head.writeUInt32LE(16, 16); head.writeUInt16LE(1, 20); head.writeUInt16LE(1, 22);
  head.writeUInt32LE(rate, 24); head.writeUInt32LE(rate * 2, 28); head.writeUInt16LE(2, 32); head.writeUInt16LE(16, 34);
  head.write('data', 36); head.writeUInt32LE(data.length, 40);
  return Buffer.concat([head, data]);
}

/** The files a synthetic library holds, by their path inside it. */
export const STOCK_FIXTURE_FILES = [
  'Backgrounds/Blue Wash.png',
  'Backgrounds/Warm Glow.png',
  'Textures/Paper Grain.png',
  'Sound Effects/Whoosh Soft.wav',
  'Sound Effects/Impact Low.wav',
] as const;

/** Write a synthetic stock library under `root`, in a collection's own folder layout. */
export async function writeStockFixture(root: string): Promise<void> {
  const make: Record<(typeof STOCK_FIXTURE_FILES)[number], () => Buffer> = {
    'Backgrounds/Blue Wash.png': () => stillPng(20, 60, 200),
    'Backgrounds/Warm Glow.png': () => stillPng(220, 120, 40),
    'Textures/Paper Grain.png': () => stillPng(230, 225, 210),
    'Sound Effects/Whoosh Soft.wav': () => toneWav(440),
    'Sound Effects/Impact Low.wav': () => toneWav(90),
  };
  for (const file of STOCK_FIXTURE_FILES) {
    await mkdir(join(root, file, '..'), { recursive: true });
    await writeFile(join(root, file), make[file]());
  }
  // A collection's own readme: not media, and left alone like everything else.
  await writeFile(join(root, 'License.txt'), 'Synthetic test library. Generated by the test suite.\n');
}

/**
 * Everything under a folder, by path: each file's bytes and modification time, and every folder.
 * Two equal snapshots mean nothing was added, removed, changed or touched.
 */
export async function snapshotTree(root: string): Promise<Record<string, string>> {
  const out: Record<string, string> = {};
  const walk = async (dir: string): Promise<void> => {
    for (const name of (await readdir(dir)).sort()) {
      const path = join(dir, name);
      const info = await stat(path);
      const key = relative(root, path);
      if (info.isDirectory()) {
        out[`${key}/`] = 'dir';
        await walk(path);
      } else {
        out[key] = `${createHash('sha256').update(await readFile(path)).digest('hex')} ${info.mtimeMs}`;
      }
    }
  };
  await walk(root);
  return out;
}

/**
 * A synthetic clip set (milestone 32): an intro, a loop and an outro as separate files, each one
 * flat color so a frame says which part it came from — red for the intro, green for the loop, blue
 * for the outro — at 10 frames a second and a small size. Made with ffmpeg's own color source.
 */
export const CLIP_SET_COLORS = { intro: [255, 0, 0], loop: [0, 255, 0], outro: [0, 0, 255] } as const;
export async function writeClipSetFixture(
  ffmpegPath: string,
  dir: string,
  name: string,
  seconds: { intro: number; loop: number; outro: number } = { intro: 1, loop: 0.5, outro: 1 },
  names: { intro: string; loop: string; outro: string } = { intro: `${name} In.mov`, loop: `${name} Loop.mov`, outro: `${name} Out.mov` },
): Promise<void> {
  const { spawnSync } = await import('node:child_process');
  await mkdir(dir, { recursive: true });
  const hex = { intro: '0xff0000', loop: '0x00ff00', outro: '0x0000ff' } as const;
  for (const part of ['intro', 'loop', 'outro'] as const) {
    const out = join(dir, names[part]);
    const run = spawnSync(ffmpegPath, ['-v', 'error', '-y', '-f', 'lavfi', '-i', `color=c=${hex[part]}:s=64x36:r=10:d=${seconds[part]}`, '-c:v', 'qtrle', out]);
    if (run.status !== 0) throw new Error(`could not make ${out}: ${run.stderr}`);
  }
}
